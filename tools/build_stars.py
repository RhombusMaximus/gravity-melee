#!/usr/bin/env python3
"""gravity-melee :: star map builder

Turns tools/map/stars.map — "The Ur-Quan Masters official star
definitions" (star/cluster name, designation, X/Y grid coords, color,
size) — into js/stars.js for the 3D hyperspace starmap.

The flat SC2 map (0..1000 grid) is scaled into world units and centered
on the map middle; each CONSTELLATION gets a stable Z-depth band (plus
per-star jitter) so clusters read as real 3D groups while you fly.

Star names/positions are Star Control II content, (c) Toys for Bob,
distributed via The Ur-Quan Masters, licensed CC BY-NC-SA 2.5.

Usage: python3 tools/build_stars.py <uqm-checkout> [out.js]
"""
import hashlib
import subprocess
import sys

S = 26.0          # grid unit -> world unit scale (map ~26000 across)
Z_SPAN = 2600.0   # constellation depth band (+/-)
Z_JITTER = 420.0


def stable(s):
    return int(hashlib.md5(s.encode()).hexdigest()[:8], 16)


def main():
    repo = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else 'js/stars.js'
    ref = 'v0.7.0-2'

    raw = subprocess.run(['git', '-C', repo, 'show', f'{ref}:tools/map/stars.map'],
                         capture_output=True, text=True)
    if raw.returncode != 0:
        raise SystemExit('could not read tools/map/stars.map from the checkout')

    stars = []          # (name, des, gx, gy, col, size, clusterIdx)
    clusters = []       # {n: name, s: [star indices]}
    cluster_at = {}

    for ln in raw.stdout.splitlines():
        ln = ln.strip()
        if not ln or ln.startswith('#'):
            continue
        parts = [p.strip() for p in ln.split(',')]
        if len(parts) < 6:
            continue
        name, des, gx, gy, col, size = parts[0], parts[1], float(parts[2]), float(parts[3]), parts[4], int(parts[5])
        ci = -1
        if des != '*':
            if name not in cluster_at:
                cluster_at[name] = len(clusters)
                clusters.append({'n': name, 's': []})
            ci = cluster_at[name]
            clusters[ci]['s'].append(len(stars))
        stars.append((name, des, gx, gy, col, size, ci))

    world = []
    sol_idx = -1
    for (name, des, gx, gy, col, size, ci) in stars:
        wx = (gx - 500.0) * S
        wy = (gy - 500.0) * S
        if ci >= 0:
            base = (stable(clusters[ci]['n']) % (2 * int(Z_SPAN))) - Z_SPAN
            z = base + (stable(name + des) % (2 * int(Z_JITTER))) - Z_JITTER
        else:
            z = (stable(name) % (2 * int(Z_SPAN))) - Z_SPAN
        world.append((name, des, round(wx, 1), round(wy, 1), round(z, 1), col, size, ci))
        if name == 'Sol' and des == '*':
            sol_idx = len(world) - 1

    if sol_idx < 0:
        raise SystemExit('Sol not found in stars.map')

    src = []
    src.append('// gravity-melee :: the SC2 hyperspace star map (generated by tools/build_stars.py)\n')
    src.append('//\n// From tools/map/stars.map — "The Ur-Quan Masters official star definitions".\n')
    src.append('// Star names and positions are Star Control II content, (c) Toys for Bob,\n')
    src.append('// distributed via The Ur-Quan Masters, licensed CC BY-NC-SA 2.5.\n')
    src.append('// Tuple: [name, designation, x, y, z, color, size, clusterIndex]\n')
    src.append('// (designation "*" = singular star; color B/R/G/Y/O/W; size 1..3).\n')
    src.append('(function (GM) {\n')
    src.append('  GM.STARS = [\n')
    for w in world:
        des = "'%s'" % w[1] if w[1] == '*' else "'%s'" % w[1]
        src.append("    ['%s', '%s', %s, %s, %s, '%s', %d, %d],\n"
                   % (w[0], w[1], w[2], w[3], w[4], w[5], w[6], w[7]))
    src.append('  ];\n')
    src.append('  GM.STAR_CLUSTERS = [\n')
    for c in clusters:
        src.append("    { n: '%s', s: [%s] },\n" % (c['n'], ', '.join(str(i) for i in c['s'])))
    src.append('  ];\n')
    src.append('  GM.SOL_INDEX = %d;\n' % sol_idx)
    src.append('})(window.GM);\n')

    text = ''.join(src)
    with open(out, 'w') as f:
        f.write(text)
    print('wrote %s: %d stars, %d clusters, Sol at index %d (%dKB)'
          % (out, len(world), len(clusters), sol_idx, len(text) // 1024))


if __name__ == '__main__':
    main()